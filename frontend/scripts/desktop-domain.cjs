'use strict'
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const root = path.join(__dirname, '..')
let stale = false
for (const name of ['cacheProjection', 'planning', 'timesheet', 'periodAvailability', 'calendar', 'date', 'clamp']) {
  const input = path.join(root, ['date', 'clamp'].includes(name) ? 'src/utils' : 'src/domain', name + '.ts')
  const source = fs.readFileSync(input, 'utf8')
  const result = ts.transpileModule(source, { fileName: input, compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, removeComments: false, newLine: ts.NewLineKind.LineFeed } })
  const code = '// Generated by scripts/desktop-domain.cjs; edit ' + path.relative(root, input).split(path.sep).join('/') + '.\n' + result.outputText.replace(/require\("(?:\.\/|@\/utils\/)(planning|timesheet|periodAvailability|calendar|date|clamp)"\)/g, 'require("./command-$1.cjs")')
  const target = path.join(root, 'desktop/command-' + name + '.cjs')
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== code) { stale = true; console.error('Stale desktop domain: ' + name) }
  } else fs.writeFileSync(target, code)
}
if (stale) process.exitCode = 1
